import type ExcelJS from "exceljs";
import type { ReviewReport, ReviewRow } from "./review-data.ts";
import type { ReviewPresentation } from "./review-presentation.ts";

// Shared by the local HTTP export and the offline report.
export async function writeReviewXlsx(
  Workbook: typeof ExcelJS.Workbook,
  rows: ReviewRow[],
  { collectSections, aiStatus, aiTypes, aiComment, textParts }: ReviewPresentation,
  report?: ReviewReport,
): Promise<Uint8Array<ArrayBuffer>> {
  const { sections } = collectSections(rows);
  const total = [...sections.values()].reduce((count, section) => count + section.entries.size, 0);
  const limitMessage = "结果超过 Excel 的行数或单元格长度限制，请缩小导出范围。";
  if (total > 1_048_575) throw new Error(limitMessage);
  const workbook = new Workbook();
  const toolLabel = report?.tool?.name && report?.tool?.version ? `${report.tool.name}@${report.tool.version}` : "";
  if (toolLabel) {
    workbook.creator = toolLabel;
    workbook.description = `Generated by ${toolLabel}`;
  }
  const sheet = workbook.addWorksheet("QA", { views: [{ state: "frozen", ySplit: 1 }] });
  const headers = ["规则类别", "文件", "句段编号", "原文", "译文", "检查说明"];
  const widths = [23, 31, 14, 42, 42, 48];
  sheet.columns = headers.map((header, index) => ({
    header, width: widths[index]!, style: { alignment: { vertical: "top", wrapText: true } },
  }));
  for (const { label, entries } of sections.values()) {
    for (const { segment, findings } of entries.values()) {
      const comments = [...new Set(findings.map((finding) => finding.message))].join("\n");
      const values = [label, segment.file, segment.segment, segment.source, segment.target, comments];
      if (values.some((value) => value.length > 32_767)) throw new Error(limitMessage);
      const row = sheet.addRow(values);
      for (const [column, side] of [[4, "source"], [5, "target"]] as const) {
        const parts = textParts(segment[side], findings, side);
        if (!parts.some(({ marked }) => marked)) continue;
        row.getCell(column).value = { richText: parts.map(({ text, marked }) => marked
          ? { text, font: { color: { argb: "FFA22628" }, bold: true, underline: true } }
          : { text }) };
      }
    }
  }
  sheet.getRow(1).font = { bold: true };
  sheet.autoFilter = { from: { row: 1, column: 1 }, to: { row: Math.max(2, sheet.rowCount), column: headers.length } };
  if (report?.configuration || toolLabel) {
    const { files = [], configuration } = report ?? {};
    const summary = workbook.addWorksheet("检查概况");
    summary.columns = [{ width: 30 }, { width: 74, style: { alignment: { wrapText: true } } }];
    if (configuration) {
      summary.addRow(["检查状态", files.some((file) => file.incomplete) ? "检查未完整完成" : "检查完成"]);
      summary.addRow(["普通 QA 检查", configuration.checks.join("、") || "未启用"]);
    }
    if (toolLabel) {
      summary.addRow(["工具版本", toolLabel]);
    }
    for (const file of files) {
      summary.addRow([file.name, file.incomplete ? file.error ?? "部分规则未完成" : `已检查 ${file.segments} 段`]);
    }
  }
  return new Uint8Array(await workbook.xlsx.writeBuffer());
}
